from datetime import date, datetime
from typing import Any

# ---------------------------------------------------------------------------
# Counter for generating slip numbers
# ---------------------------------------------------------------------------
_slip_counter: int = 1000


def generate_slip_no() -> str:
    global _slip_counter
    _slip_counter += 1
    today = datetime.utcnow().strftime("%Y%m%d")
    return f"TXN-{today}-{_slip_counter:04d}"


def to_serializable(obj: Any) -> Any:
    """Recursively convert date/datetime objects in dicts/lists to ISO strings."""
    if isinstance(obj, dict):
        return {k: to_serializable(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [to_serializable(i) for i in obj]
    if isinstance(obj, datetime):
        return obj.isoformat()
    if isinstance(obj, date):
        return obj.isoformat()
    return obj


