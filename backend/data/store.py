def get_user_by_username(username: str) -> dict | None:
    """Lookup a user by username."""
    for user in USERS.values():
        if user["username"] == username:
            return user
    return None


def get_transaction_by_id(txn_id: str) -> dict | None:
    """Lookup a transaction by id."""
    for txn in TRANSACTIONS:
        if txn["id"] == txn_id:
            return txn
    return None


def get_bank_entry_by_id(entry_id: str) -> dict | None:
    """Look up a bank statement entry by id across all statements."""
    for stmt in BANK_STATEMENTS:
        for entry in stmt.get("entries", []):
            if entry["id"] == entry_id:
                return entry
    return None


def get_scheme_by_id(scheme_id: str) -> dict | None:
    """Lookup a scheme by id."""
    for scheme in SCHEMES:
        if scheme["id"] == scheme_id:
            return scheme
    return None


def get_bank_account_by_id(ba_id: str) -> dict | None:
    """Lookup a bank account by id."""
    for ba in BANK_ACCOUNTS:
        if ba["id"] == ba_id:
            return ba
    return None


def get_bank_account_for_scheme(scheme_id: str) -> dict | None:
    """Return the bank account associated with a scheme."""
    for ba in BANK_ACCOUNTS:
        if ba["scheme_id"] == scheme_id:
            return ba
    return None


def get_statements_for_account(ba_id: str) -> list[dict]:
    """Return all bank statements for a given bank account."""
    return [s for s in BANK_STATEMENTS if s["bank_account_id"] == ba_id]
